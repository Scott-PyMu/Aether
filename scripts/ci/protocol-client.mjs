#!/usr/bin/env node
/**
 * `packages/protocol/src/client.ts` 生成器（M9-08 DoD-1/DoD-2；ADR-029 §7）。
 *
 * 单一事实来源：
 * - 命令名 / 路由 / 参数风格 / 请求 DTO：`command-manifest.json`
 *   （由 `scripts/ci/command-manifest.mjs` 从 `aether-app` 清单生成）；
 * - 32 IPC 错误码 + 9 业务码：`error_codes.json`
 *   （由 `scripts/ci/error-codes.mjs` 从 `aether-app` 生成）；
 * - 请求/事件 DTO 类型：`types.ts`（由 `m9_08_protocol.rs` 的 specta 导出生成）。
 *
 * 生成物禁止手改（AGENTS §2.8）。用法：
 *   node scripts/ci/protocol-client.mjs generate
 *   node scripts/ci/protocol-client.mjs check
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const MANIFEST = "packages/protocol/src/command-manifest.json";
const ERROR_CODES = "packages/protocol/src/error_codes.json";
const TARGET = "packages/protocol/src/client.ts";

const MODE = process.argv.slice(2).find((arg) => !arg.startsWith("--")) ?? "check";
if (MODE !== "generate" && MODE !== "check") {
  console.error(`[protocol-client] 未知模式：${MODE}（可选 generate / check）`);
  process.exit(2);
}

function readJson(rel) {
  return JSON.parse(readFileSync(path.join(root, rel), "utf8"));
}

function camel(name) {
  return name.replace(/_([a-z0-9])/g, (_, char) => char.toUpperCase());
}

function unique(values) {
  return [...new Set(values)];
}

function assertManifest(manifest) {
  const counts = manifest.counts ?? {};
  if (counts.total !== 63 || counts.daemon !== 59 || counts.shell !== 4) {
    throw new Error(
      `[protocol-client] 路由计数 ${counts.daemon}/${counts.shell}/${counts.total} ≠ 59/4/63`,
    );
  }
  if (counts.ui !== 61 || counts.reserved !== 2) {
    throw new Error(`[protocol-client] UI 暴露 ${counts.ui} / 保留 ${counts.reserved} ≠ 61/2`);
  }
  if (!Array.isArray(manifest.commands) || manifest.commands.length !== 63) {
    throw new Error("[protocol-client] command-manifest.commands 必须恰好 63 条");
  }
}

function errorUnion(codes) {
  return codes.map((code) => `  | ${JSON.stringify(code)}`).join("\n");
}

/**
 * 构建 `client.ts` 文本（稳定序列化：LF + 末尾换行）。
 * 导出供 `verify:m9-08` 逐字节比较，避免「生成器自己和自己一致」。
 */
export function buildProtocolClient() {
  const manifest = readJson(MANIFEST);
  const errors = readJson(ERROR_CODES);
  assertManifest(manifest);
  if (!Array.isArray(errors.ipc) || errors.ipc.length !== 32) {
    throw new Error("[protocol-client] error_codes.json 的 ipc 必须恰好 32 项");
  }
  if (!Array.isArray(errors.business) || errors.business.length !== 9) {
    throw new Error("[protocol-client] error_codes.json 的 business 必须恰好 9 项");
  }

  const commands = manifest.commands;
  const commandsWithParams = commands
    .filter((entry) => entry.params?.style === "strict" || entry.params?.style === "no_params")
    .map((entry) => entry.params.dto)
    .filter((dto) => typeof dto === "string");
  const requestTypes = unique(commandsWithParams).sort();

  const commandNames = commands.map((entry) => entry.name);
  const daemon = commands.filter((entry) => entry.route === "daemon").map((entry) => entry.name);
  const shell = commands.filter((entry) => entry.route === "shell").map((entry) => entry.name);
  const reserved = commands
    .filter((entry) => entry.exposure === "reserved")
    .map((entry) => entry.name);

  const ipcCodes = errors.ipc.map((entry) => entry.code);
  const businessCodes = errors.business.map((entry) => entry.code);

  const methodSignatures = commands.map((entry) => {
    const method = camel(entry.name);
    const dto = entry.params?.dto;
    if (entry.params?.style === "none") {
      return `  /** \`${entry.name}\`（无参数）。 */\n  ${method}<T = unknown>(): Promise<T>;`;
    }
    if (entry.params?.style === "no_params") {
      return `  /** \`${entry.name}\`（无参数或空对象；保留可选过滤字段）。 */\n  ${method}<T = unknown>(params?: ${dto}): Promise<T>;`;
    }
    return `  /** \`${entry.name}\`（严格参数）。 */\n  ${method}<T = unknown>(params: ${dto}): Promise<T>;`;
  });

  const implementations = commands.map((entry) => {
    const method = camel(entry.name);
    if (entry.params?.style === "none") {
      return `    async ${method}<T = unknown>(): Promise<T> {\n      return call<T>("${entry.name}");\n    },`;
    }
    return `    async ${method}<T = unknown>(params?: ${entry.params.dto}): Promise<T> {\n      return call<T>("${entry.name}", params);\n    },`;
  });

  return `// This file has been generated by scripts/ci/protocol-client.mjs (M9-08). Do not edit manually.
// Source: packages/protocol/src/{command-manifest.json,error_codes.json,types.ts}

import type {
  AetherEvent,
${requestTypes.map((name) => `  ${name},`).join("\n")}
} from "./types";

/** 域事件通道名（D7 / ADR-029 §4.4；与 \`aether.event\` / \`aether:event\` 一一映射）。 */
export const AETHER_EVENT_CHANNEL = "aether:event" as const;
/** Electron preload RPC 通道名（ADR-029 §5.1）。 */
export const AETHER_RPC_CHANNEL = "aether:rpc" as const;

/** 63 条命令（顺序 = command-manifest；59 daemon + 4 shell）。 */
export const COMMANDS = [
${commandNames.map((name) => `  ${JSON.stringify(name)},`).join("\n")}
] as const;
export type AetherCommand = (typeof COMMANDS)[number];

/** 59 条 daemon 命令。 */
export const DAEMON_COMMANDS = [
${daemon.map((name) => `  ${JSON.stringify(name)},`).join("\n")}
] as const;
export type AetherDaemonCommand = (typeof DAEMON_COMMANDS)[number];

/** 4 条壳本地命令（\`app_exit\`/\`app_restart\`/\`ref_pick\`/\`startup_pick_target\`）。 */
export const SHELL_COMMANDS = [
${shell.map((name) => `  ${JSON.stringify(name)},`).join("\n")}
] as const;
export type AetherShellCommand = (typeof SHELL_COMMANDS)[number];

/** 2 条保留命令（\`startup_get\`/\`startup_migrate\`；UI 不暴露）。 */
export const RESERVED_COMMANDS = [
${reserved.map((name) => `  ${JSON.stringify(name)},`).join("\n")}
] as const;
export type AetherReservedCommand = (typeof RESERVED_COMMANDS)[number];

/** 32 个 IPC 错误码（\`IpcErrorCode::as_str()\` 唯一来源；ADR-029 §4.3）。 */
export type AetherErrorCode =
${errorUnion(ipcCodes)};

/** 9 个业务码（\`error.data.business_code\`；ADR-018 A-7）。 */
export type AetherBusinessCode =
${errorUnion(businessCodes)};

/** 事件回调（9 字段信封；EventStore 直接 ingest）。 */
export type AetherEventHandler = (event: AetherEvent) => void;

/** app/daemon/core/协议/Electron 运行时版本（preload \`version\`）。 */
export interface AetherVersionInfo {
  app: string;
  daemon?: string;
  core?: string;
  protocol?: string;
  electron?: string;
  chrome?: string;
  node?: string;
}

/** preload 的 \`rpc\` 可克隆信封（ADR-029 §5.1；contextBridge 不保留自定义错误字段）。 */
export interface AetherRpcEnvelope {
  ok: boolean;
  result?: unknown;
  error?: {
    code: number;
    message: string;
    data?: {
      aether_code?: string;
      business_code?: string;
      details?: unknown;
      field?: string;
      [key: string]: unknown;
    };
  };
}

/**
 * preload 暴露的唯一桥接面（ADR-029 §5.1）：
 * \`rpc\` / \`onEvent\` / \`offEvent\` / \`pathForFile\` / \`version\`。
 * renderer 不得直接访问 \`ipcRenderer\` / \`require\` / \`process\`。
 */
export interface AetherBridge {
  rpc(method: string, params?: unknown): Promise<AetherRpcEnvelope>;
  onEvent(handler: AetherEventHandler): void;
  offEvent(handler: AetherEventHandler): void;
  /** 唯一文件路径 API（preload 内 \`webUtils.getPathForFile\`；只返回路径字符串）。 */
  pathForFile(file: File): string;
  version(): AetherVersionInfo | Promise<AetherVersionInfo>;
}

declare global {
  interface Window {
    /** Electron preload 暴露的唯一桥接面（sandboxed renderer；ADR-029 §5.1）。 */
    aether?: AetherBridge;
  }
}

export interface AetherErrorInit {
  aether_code: string;
  business_code?: string | null;
  details?: unknown;
  message?: string;
  field?: string | null;
}

/**
 * 结构化错误（ADR-029 §4.3）：\`aether_code\` 只取 32 枚举；
 * \`business_code\` 优先用于业务分支；\`code\` 保留为 \`aether_code\` 的兼容读取。
 */
export class AetherError extends Error {
  readonly aether_code: string;
  readonly business_code?: string;
  readonly details?: unknown;
  readonly field?: string;

  constructor(init: AetherErrorInit) {
    super(init.message ?? init.aether_code);
    this.name = "AetherError";
    this.aether_code = init.aether_code;
    if (init.business_code !== undefined && init.business_code !== null) {
      this.business_code = init.business_code;
    }
    if (init.details !== undefined) {
      this.details = init.details;
    }
    if (init.field !== undefined && init.field !== null) {
      this.field = init.field;
    }
  }

  /** 兼容既有 UI：\`code\` = \`aether_code\`（业务判定请用 \`primary_code\`）。 */
  get code(): string {
    return this.aether_code;
  }

  /** ADR-029 §4.3 判定顺序：\`business_code\`（若存在）→ \`aether_code\`。 */
  get primary_code(): string {
    return this.business_code ?? this.aether_code;
  }

  static from(error: unknown): AetherError {
    const normalized = tryAetherError(error);
    if (normalized) {
      return normalized;
    }
    const message = error instanceof Error ? error.message : String(error);
    return new AetherError({ aether_code: "internal", message });
  }
}

function asRecord(value: unknown): Record<string, unknown> | null {
  return typeof value === "object" && value !== null
    ? (value as Record<string, unknown>)
    : null;
}

function stringField(
  record: Record<string, unknown> | null,
  key: string,
): string | undefined {
  if (!record) {
    return undefined;
  }
  const value = record[key];
  return typeof value === "string" && value.length > 0 ? value : undefined;
}

/** JSON-RPC 传输/类别码 → 可用 \`aether_code\`（无法映射时 internal）。 */
function transportCodeToAetherCode(code: number): AetherErrorCode {
  switch (code) {
    case -32700:
    case -32600:
      return "invalid_json";
    case -32601:
      return "not_implemented";
    case -32602:
      return "invalid_value";
    case -32001:
    case -32006:
      return "invalid_value";
    case -32002:
    case -32004:
      return "core_not_ready";
    case -32003:
      return "too_large";
    case -32005:
      return "startup_blocked";
    default:
      return "internal";
  }
}

/**
 * 把预加载/JSON-RPC/旧壳错误归一为 {@link AetherError}；非结构化错误返回 \`null\`。
 *
 * 兼容顺序：\`aether_code\` → \`data.aether_code\` → 旧 \`code\`（字符串）→
 * JSON-RPC 数值码（映射见 {@link transportCodeToAetherCode}）。
 */
export function tryAetherError(error: unknown): AetherError | null {
  if (error instanceof AetherError) {
    return error;
  }
  const record = asRecord(error);
  if (!record) {
    return null;
  }
  const data = asRecord(record.data);
  const directCode = stringField(record, "aether_code");
  const dataCode = stringField(data, "aether_code");
  const legacyCode = stringField(record, "code");
  const numericCode = typeof record.code === "number" ? record.code : null;
  const aetherCode = directCode ?? dataCode ?? legacyCode ?? null;
  const transportCode =
    aetherCode === null && numericCode !== null
      ? transportCodeToAetherCode(numericCode)
      : null;
  if (aetherCode === null && transportCode === null) {
    return null;
  }
  const businessCode =
    stringField(record, "business_code") ?? stringField(data, "business_code");
  const field = stringField(record, "field") ?? stringField(data, "field");
  const details = record.details ?? data?.details ?? (numericCode !== null ? record : undefined);
  const message =
    stringField(record, "message") ??
    stringField(data, "message") ??
    aetherCode ??
    transportCode ??
    "internal";
  return new AetherError({
    aether_code: aetherCode ?? transportCode ?? "internal",
    business_code: businessCode,
    details,
    message,
    field,
  });
}

/** 结构化错误码（\`business_code\` 优先，其次 \`aether_code\`）；非结构化返回 \`null\`。 */
export function aetherErrorCode(error: unknown): string | null {
  return tryAetherError(error)?.primary_code ?? null;
}

/** 展示文本（\`message\` 优先，兜底 \`String(error)\`）。 */
export function describeAetherError(error: unknown): string {
  const normalized = tryAetherError(error);
  return normalized?.message ?? String(error);
}

/** 63 方法 typed client + 底层 \`rpc\` / \`onEvent\`。 */
export interface AetherClient {
  /** 底层 JSON-RPC 调用（method 仍受 63 命令联合类型约束）。 */
  rpc<T = unknown>(method: AetherCommand, params?: unknown): Promise<T>;
  /** 订阅 \`aether:event\`；返回解除函数。 */
  onEvent(handler: AetherEventHandler): () => void;
  /** app/daemon/core 版本（preload 透传）。 */
  version(): AetherVersionInfo | Promise<AetherVersionInfo>;

${methodSignatures.join("\n\n")}
}

const COMMAND_SET: ReadonlySet<string> = new Set(COMMANDS);

export type AetherBridgeProvider = AetherBridge | (() => AetherBridge);

function bridgeOf(provider: AetherBridgeProvider): AetherBridge {
  return typeof provider === "function" ? provider() : provider;
}

/** 用注入的桥接面构造 client（测试/Electron preload 共用）。 */
export function createAetherClient(provider: AetherBridgeProvider): AetherClient {
  const call = async <T>(method: AetherCommand, params?: unknown): Promise<T> => {
    if (!COMMAND_SET.has(method)) {
      throw new AetherError({
        aether_code: "invalid_enum",
        message: \`未知命令：\${method}（不在 63 命令清单内）\`,
        field: "method",
      });
    }
    const envelope = await bridgeOf(provider).rpc(method, params);
    if (envelope === null || typeof envelope !== "object" || typeof envelope.ok !== "boolean") {
      throw new AetherError({
        aether_code: "internal",
        message: "preload rpc 响应形状非法（缺少 ok 信封）",
        details: envelope,
      });
    }
    if (envelope.ok) {
      return envelope.result as T;
    }
    throw (
      tryAetherError(envelope.error) ??
      new AetherError({
        aether_code: "internal",
        message: "preload rpc 返回失败但缺少结构化错误",
        details: envelope,
      })
    );
  };

  return {
    rpc: call,
    onEvent(handler) {
      const bridge = bridgeOf(provider);
      bridge.onEvent(handler);
      return () => bridge.offEvent(handler);
    },
    version() {
      return bridgeOf(provider).version();
    },
${implementations.join("\n")}
  };
}

/** 生产客户端：首次调用时解析 preload 暴露的 \`window.aether\`。 */
export const client: AetherClient = createAetherClient(() => {
  const scope = globalThis as typeof globalThis & { aether?: AetherBridge };
  if (!scope.aether) {
    throw new AetherError({
      aether_code: "core_not_ready",
      message: "Electron preload 未就绪（window.aether 缺失）",
    });
  }
  return scope.aether;
});

/** 显式别名（与 \`client\` 同引用；便于调用方表达意图）。 */
export const aetherClient: AetherClient = client;
`;
}

export function renderProtocolClient() {
  return buildProtocolClient();
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rendered = renderProtocolClient();
  const targetPath = path.join(root, TARGET);
  if (MODE === "generate") {
    writeFileSync(targetPath, rendered, "utf8");
    console.log(`[protocol-client] 生成完成：${TARGET}（63 方法；59/4；32+9 错误码）`);
    process.exit(0);
  }
  let current;
  try {
    current = readFileSync(targetPath, "utf8");
  } catch {
    console.error(`[protocol-client] 阻断：生成物缺失（${TARGET}）。先运行 generate。`);
    process.exit(1);
  }
  if (current !== rendered) {
    console.error(`[protocol-client] 阻断：${TARGET} 与重新生成结果不一致（diff=0 要求）。`);
    process.exit(1);
  }
  console.log("[protocol-client] 通过：63 方法 / 59+4 / 32+9 / diff=0");
}
